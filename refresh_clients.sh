#!/usr/bin/env bash
set -euo pipefail

# Path to the wfn executable; override with the WFN_PATH env var
WFN="${WFN_PATH:-wfn}"

# Check wfn exists
if ! command -v "$WFN" >/dev/null 2>&1; then
  echo "Error: '$WFN' WebFunction CLI tool was not found in your PATH." >&2
  echo "You can specify its location using the WFN_PATH environment variable, e.g.:" >&2
  echo "  WFN_PATH=/path/to/wfn $0" >&2
  echo "If you don't have the tool, get/build it from https://github.com/webfunction-protocol/webfunction-cli" >&2
  exit 1
fi

# Generate code for clients
"$WFN" codegen --target php --url https://api.reservepay.com/merchants -o ./src/Merchant.php --namespace Reservepay\\Merchant
"$WFN" codegen --target php --url https://api.reservepay.com/terminals -o ./src/Terminal.php --namespace Reservepay\\Terminal
"$WFN" codegen --target php --url https://api.reservepay.com/sdk -o ./src/SDK.php --namespace Reservepay\\SDK

# Generate the autoload files so the library can be tested locally (needs composer)
if command -v composer >/dev/null 2>&1; then
  composer dump-autoload
  echo "Autoload files have been generated by composer and placed in 'vendor/' so the library can be tested locally"
else
  echo "If you want to test the library locally - please install 'composer' before generating the clients"
fi
